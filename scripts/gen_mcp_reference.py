#!/usr/bin/env python3
"""Generate docs/en/mcp-tools.md from the MCP server's tool definitions.

    python scripts/gen_mcp_reference.py            # rewrite the file
    python scripts/gen_mcp_reference.py --check    # exit 1 if it is stale

tests/test_docs.py runs the check, so the reference cannot drift from code.
"""

from __future__ import annotations

import asyncio
import importlib.util
import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[1]
OUT = REPO / "docs" / "en" / "mcp-tools.md"

GROUPS = [
    ("upq_", "Market data (UPQ)"),
    ("esp_", "News and events (ESP)"),
    ("research_", "Research"),
    ("pmb_", "Paper broker (PMB)"),
]
# Parameters the hub fills in; documented once in the header instead.
HIDDEN = {"ctx"}


def load_server():
    if str(REPO) not in sys.path:
        sys.path.insert(0, str(REPO))
    spec = importlib.util.spec_from_file_location("_qfz_mcp_server_doc", REPO / "mcp" / "server.py")
    mod = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(mod)
    return mod


def _type(schema: dict) -> str:
    if "anyOf" in schema:
        parts = [_type(s) for s in schema["anyOf"] if s.get("type") != "null"]
        return " \\| ".join(parts) or "any"
    if "enum" in schema:
        return " \\| ".join(json.dumps(v) for v in schema["enum"])
    t = schema.get("type", "any")
    if t == "array":
        return f"list[{_type(schema.get('items', {}))}]"
    return {"string": "str", "integer": "int", "number": "float", "boolean": "bool", "object": "dict"}.get(t, t)


def _summary(doc: str) -> tuple[str, dict[str, str]]:
    """First paragraph, and per-argument text from a Google-style Args block."""
    lines = (doc or "").strip().splitlines()
    para: list[str] = []
    for ln in lines:
        if not ln.strip():
            break
        para.append(ln.strip())
    args: dict[str, str] = {}
    in_args, cur = False, None
    for ln in lines:
        s = ln.strip()
        if s in ("Args:", "Arguments:"):
            in_args = True
            continue
        if in_args:
            if s.endswith(":") and s[:-1] in ("Returns", "Raises", "Example", "Examples"):
                break
            m = re.match(r"^([A-Za-z_]\w*(?:\s*[/,]\s*[A-Za-z_]\w*)*)\s*:\s*(.*)$", s)
            if m and not ln.startswith(" " * 12):
                names = re.split(r"\s*[/,]\s*", m.group(1))
                cur = names
                for n in names:
                    args[n] = m.group(2).strip()
            elif cur and s:
                for n in cur:
                    args[n] += " " + s
    return " ".join(para), args


def render(tools) -> str:
    out = [
        "# MCP tool reference",
        "",
        "> Generated by `scripts/gen_mcp_reference.py` from `mcp/server.py`; do not edit by hand.",
        "",
        f"The hub serves {len(tools)} tools at `/mcp` (streamable HTTP; `Authorization: Bearer qfz_…`).",
        "Data tools accept an optional `session_id`; a connection-level `X-QFZ-Session` header takes",
        "precedence and cannot be overridden by the agent (see the platform guide, section 1).",
        "",
    ]
    by_group: dict[str, list] = {title: [] for _, title in GROUPS}
    for t in sorted(tools, key=lambda t: t.name):
        title = next((g for p, g in GROUPS if t.name.startswith(p)), "Other")
        by_group.setdefault(title, []).append(t)
    out.append("| group | tools |")
    out.append("|---|---|")
    for title, ts in by_group.items():
        if ts:
            out.append(f"| {title} | " + ", ".join(f"[`{t.name}`](#{t.name})" for t in ts) + " |")
    out.append("")
    for title, ts in by_group.items():
        if not ts:
            continue
        out += [f"## {title}", ""]
        for t in ts:
            summary, arg_doc = _summary(t.description)
            out += [f"### {t.name}", "", summary or "(no description)", ""]
            props = (t.inputSchema or {}).get("properties", {})
            required = set((t.inputSchema or {}).get("required", []))
            rows = [(k, v) for k, v in props.items() if k not in HIDDEN]
            if rows:
                out += ["| parameter | type | required | default | description |", "|---|---|---|---|---|"]
                for k, v in rows:
                    default = "" if k in required or "default" not in v else f"`{json.dumps(v['default'])}`"
                    desc = arg_doc.get(k, v.get("description", "")).replace("|", "\\|")
                    out.append(f"| `{k}` | {_type(v)} | {'yes' if k in required else ''} | {default} | {desc} |")
                out.append("")
    return "\n".join(out).rstrip() + "\n"


def main(argv=None) -> int:
    srv = load_server()
    tools = asyncio.run(srv.mcp.list_tools())
    text = render(tools)
    if "--check" in (argv or sys.argv[1:]):
        if not OUT.exists() or OUT.read_text() != text:
            print(f"{OUT} is stale; run python scripts/gen_mcp_reference.py", file=sys.stderr)
            return 1
        return 0
    OUT.write_text(text)
    print(f"{len(tools)} tools -> {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
